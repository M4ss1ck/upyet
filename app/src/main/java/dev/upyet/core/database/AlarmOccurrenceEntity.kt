package dev.upyet.core.database

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey

@Entity(
    tableName = "alarm_occurrences",
    indices = [Index("alarmId")],
)
data class AlarmOccurrenceEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val alarmId: Long,
    val scheduledFor: Long,
    val triggeredAt: Long?,
    val activityVisibleAt: Long?,
    val dismissedAt: Long?,
    val outcome: String,
    val parentOccurrenceId: Long?,
    @ColumnInfo(defaultValue = "ALARM") val source: String = "ALARM",
    val timerAttribution: String? = null,
) {
    companion object {
        /**
         * The `alarmId` of a timer occurrence, which has no alarm. Autogenerated alarm ids start at 1, so 0 never
         * names one. The column stays NOT NULL because a nullable column would make SQLite rebuild the table and
         * rewrite every row, which the migration deliberately avoids.
         */
        const val NO_ALARM_ID = 0L
    }
}
