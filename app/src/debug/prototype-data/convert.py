#!/usr/bin/env python3
"""Deterministic converter: Natural Earth GeoJSON -> the throwaway prototype's two assets.

PROTOTYPE for #15, throwaway, debug-only. This script is not part of the build: no Gradle task runs it,
the generated files are committed next to it, and the real import pipeline is a separate, later change.
It exists so the assets the prototype reads can be regenerated byte-for-byte from the public-domain
Natural Earth download instead of being an unexplained blob.

Run it with the interpreter sealed off from the environment and from `.pyc` litter:

    python3 -I app/src/debug/prototype-data/convert.py \\
        /tmp/clock-tabs/research/places.geojson \\
        /tmp/clock-tabs/research/land.geojson \\
        app/src/debug/assets/prototype

Inputs (Natural Earth, public domain - no attribution required, nothing here is copied code):
  * places.geojson  ne_10m_populated_places: one Point per populated place, with NAMEASCII, NAME_ES,
                    ISO_A2, TIMEZONE, LATITUDE, LONGITUDE and POP_MAX.
  * land.geojson    ne_110m_land: 1:110m land polygons, one geometry per landmass.

Outputs (both written into the third argument, which is created if missing):

  cities.tsv
    One row per place with POP_MAX >= 15000 and a non-empty TIMEZONE; everything else is skipped,
    because a place without a zone is a clock that cannot be drawn and the real pipeline fills that
    gap later. Tab separated, header line first, no quoting: name and country fields have tabs and
    line breaks collapsed to single spaces at write time, so a tab is always a field separator.
    Columns: nameascii, name_es, iso_a2, timezone, latitude, longitude, pop_max.
      - latitude/longitude are printed with exactly 4 decimals (about 11 m, far finer than any pixel
        the prototype's 360x150 degree map can show) so the file is stable under re-running.
      - name_es falls back to nameascii when Natural Earth has no Spanish name for the place, so the
        prototype's Spanish display name is never blank.
      - iso_a2 may be "-99" where Natural Earth does not know the country; it is passed through as-is.
    Sorted by pop_max descending, then nameascii, then iso_a2, then latitude, then longitude - a
    total order, so two runs over the same input produce identical bytes.

  land.bin
    The land polygons quantised to 1/100 degree, little-endian, in this layout:

        magic         4 bytes  b"UPLD" (version 1, no trailing version byte: the magic carries it)
        ring_count    uint32   number of rings that follow
        then, per ring:
          point_count uint32   number of (lon, lat) pairs in this ring
          points      point_count * (int16 lon, int16 lat), each = round(degrees * 100)

    Interior rings (holes, e.g. the Caspian shore) are written as their own ring and filled even-odd
    by the reader, so ring order is preserved as it appears in the GeoJSON and hole-ness is decided
    by the reader's fill rule rather than by a flag this format would have to invent.
    1/100 degree keeps every vertex inside int16 (|18000| and |9000| well under 32767) and is finer
    than a 1080p phone can draw on a map this size, so the quantisation is lossless in practice.
    Polygons are not clipped: the prototype's canvas clips them against its own latitude crop.

Both files are written atomically (temp file, then rename) so an interrupted run cannot leave a
half-written asset for the build to package.
"""

import json
import os
import struct
import sys

# POP_MAX below this is a village: the prototype's search results would be a list of hamlets.
MIN_POP = 15000

# Hundredths of a degree: the quantisation step of land.bin.
DEGREE_SCALE = 100

CITIES_HEADER = ("nameascii", "name_es", "iso_a2", "timezone", "latitude", "longitude", "pop_max")


def squashed(value):
    """Tab/newline-free single-line form of a name field, so the TSV needs no quoting at all."""
    return " ".join(str(value or "").split())


def lon_lat(properties):
    """Coordinates from the place properties, which are the row's own, not the geometry's centroid."""
    return float(properties["LATITUDE"]), float(properties["LONGITUDE"])


def read_cities(places_path):
    with open(places_path, "r", encoding="utf-8") as handle:
        document = json.load(handle)
    features = document["features"]
    rows = []
    skipped_no_zone = 0
    skipped_small = 0
    for feature in features:
        properties = feature["properties"]
        timezone = squashed(properties.get("TIMEZONE"))
        if not timezone:
            skipped_no_zone += 1
            continue
        population = int(properties.get("POP_MAX") or 0)
        if population < MIN_POP:
            skipped_small += 1
            continue
        name_ascii = squashed(properties.get("NAMEASCII")) or squashed(properties.get("NAME"))
        if not name_ascii:
            continue
        latitude, longitude = lon_lat(properties)
        rows.append(
            (
                name_ascii,
                squashed(properties.get("NAME_ES")) or name_ascii,
                squashed(properties.get("ISO_A2")),
                timezone,
                latitude,
                longitude,
                population,
            )
        )
    # Total order: no two rows can compare equal unless they are the same place, so the bytes never move.
    rows.sort(key=lambda row: (-row[6], row[0], row[2], row[4], row[5]))
    stats = {
        "features": len(features),
        "written": len(rows),
        "skipped_no_zone": skipped_no_zone,
        "skipped_small": skipped_small,
    }
    return rows, stats


def write_cities(rows, out_path):
    lines = ["\t".join(CITIES_HEADER)]
    for name_ascii, name_es, iso_a2, timezone, latitude, longitude, population in rows:
        lines.append(
            "\t".join(
                (
                    name_ascii,
                    name_es,
                    iso_a2,
                    timezone,
                    "{:.4f}".format(latitude),
                    "{:.4f}".format(longitude),
                    str(population),
                )
            )
        )
    payload = "\n".join(lines) + "\n"
    write_atomically(out_path, payload.encode("utf-8"))


def read_land_rings(land_path):
    with open(land_path, "r", encoding="utf-8") as handle:
        document = json.load(handle)
    rings = []
    for feature in document["features"]:
        geometry = feature.get("geometry")
        if not geometry:
            continue
        kind = geometry["type"]
        coordinates = geometry["coordinates"]
        polygons = coordinates if kind == "MultiPolygon" else [coordinates]
        for polygon in polygons:
            for ring in polygon:
                rings.append(ring)
    return rings


def quantise(value):
    scaled = int(round(value * DEGREE_SCALE))
    if not -32768 <= scaled <= 32767:
        raise ValueError("coordinate {!r} does not fit in int16 at 1/100 degree".format(value))
    return scaled


def write_land(rings, out_path):
    chunk = [b"UPLD", struct.pack("<I", len(rings))]
    points = 0
    for ring in rings:
        chunk.append(struct.pack("<I", len(ring)))
        for longitude, latitude in ring:
            chunk.append(struct.pack("<hh", quantise(longitude), quantise(latitude)))
            points += 1
    write_atomically(out_path, b"".join(chunk))
    return {"rings": len(rings), "points": points}


def write_atomically(path, payload):
    temporary = path + ".tmp"
    with open(temporary, "wb") as handle:
        handle.write(payload)
    os.replace(temporary, path)


def main(argv):
    if len(argv) != 4:
        sys.stderr.write(
            "usage: convert.py <places.geojson> <land.geojson> <output-dir>\n"
        )
        return 2
    places_path, land_path, out_dir = argv[1], argv[2], argv[3]
    os.makedirs(out_dir, exist_ok=True)

    city_rows, city_stats = read_cities(places_path)
    write_cities(city_rows, os.path.join(out_dir, "cities.tsv"))

    land_rings = read_land_rings(land_path)
    land_stats = write_land(land_rings, os.path.join(out_dir, "land.bin"))

    print("places: {} features, {} written to cities.tsv".format(city_stats["features"], city_stats["written"]))
    print("        skipped {} without TIMEZONE, {} under POP_MAX {}".format(
        city_stats["skipped_no_zone"], city_stats["skipped_small"], MIN_POP))
    print("land:   {} rings, {} points written to land.bin".format(land_stats["rings"], land_stats["points"]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
